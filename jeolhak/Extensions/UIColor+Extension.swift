import UIKit

extension UIColor {
    static var mainPink: UIColor {
        return UIColor(red: 255/255, green: 110/255, blue: 145/255, alpha: 1.0)
    }
    
    static var mainMint: UIColor {
        return UIColor(red: 64/255, green: 183/255, blue: 201/255, alpha: 1.0)
    }
}
